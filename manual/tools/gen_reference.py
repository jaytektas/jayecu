def gen_sensor_types(schema):
    types = schema["sensor_types"]
    sensors = schema.get("sensors") or []
    by_type = {}
    for s in sensors:
        by_type.setdefault(s.get("type"), []).append(s)
    out = [HEADER, "# Sensor types\n\n",
           "Every sensor has a **type**: what it measures, in which units, over which range, how often it is\n"
           "read, and which checks it can run (chapter 17). The ECU always works in these units; the studio\n"
           "can show others (Preferences ▸ Units).\n\n",
           "| Type | Units | Range | Read at | Checks |\n|---|---|---|---|---|\n"]
    for t in types:
        diags = ", ".join(t.get("diagnostics", []))
        rate = f"{t['update_hz']} Hz" if "update_hz" in t else ""
        out.append(f"| **{t['id']}** | {cell(t.get('units', ''))} | {num(t.get('min'))} to {num(t.get('max'))} | "
                   f"{rate} | {cell(diags)} |\n")
    out.append("\n## The sensors of each type\n\n")
    for t in types:
        ss = by_type.get(t["id"], [])
        if not ss:
            continue
        out.append(f"### {t['id']}\n\n| Sensor | Interfaces |\n|---|---|\n")
        for s in ss:
            out.append(f"| {cell(s.get('name', s['id']))} | {cell(', '.join(s.get('interfaces', [])))} |\n")
        out.append("\n")
    (REF / "sensor-types.md").write_text("".join(out))


