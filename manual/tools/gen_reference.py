#!/usr/bin/env python3
"""The generated reference pages of the manual (Part VII) — STANDARD.md §7.

    python3 manual/tools/gen_reference.py           (after `make codegen`)

Writes, from the definition the studio itself loads (shared/tuneit-meta.json) and the schema:

    manual/docs/reference/channels.md          every output channel
    manual/docs/reference/dtc.md               every trouble code the definition names
    manual/docs/reference/sensor-types.md      every sensor type, and the sensors of each type
    manual/docs/reference/output-templates.md  every output template and its parameters
    manual/docs/reference/lua-api.md           the Lua functions and callbacks
    manual/docs/reference/trigger-wheels.md    the trigger wheel library, each wheel drawn
    manual/docs/img/wheels/<wheel>.svg         …its diagrams

Never edit the output: fix the source (schema help, the meta's own text), run `make codegen`, run this.
"""
import json, pathlib, re

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
META = ROOT / "shared" / "tuneit-meta.json"
SCHEMA = ROOT / "definition" / "ecu.schema.yaml"
DOCS = ROOT / "manual" / "docs"
REF = DOCS / "reference"
WHEELS = DOCS / "img" / "wheels"

HEADER = "<!-- GENERATED by manual/tools/gen_reference.py from shared/tuneit-meta.json — do not edit. -->\n\n"


def load_meta():
    return json.loads(META.read_bytes()[:-4])       # a .meta is the JSON body plus a 4-byte CRC32 footer


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def num(v, digits=None):
    if isinstance(v, (int, float)):
        if digits is not None:
            return f"{v:.{digits}f}"
        return f"{v:g}"
    return str(v)


