KIND = {0: "PWM", 1: "Digital"}


def gen_output_templates(m):
    out = [HEADER, "# Output templates\n\n",
           "An output template fills in a Generic output for a common job — its conditions, its value and its\n"
           "parameters — through the output's wizard (chapter 18). Everything it sets can be changed\n"
           "afterwards.\n\n"]
    for t in m["output_templates"]:
        out.append(f"## {t['name']}\n\n{cell(t.get('blurb', ''))}\n\n")
        if t.get("detail"):
            out.append(f"{t['detail'].strip()}\n\n")
        out.append(f"Kind: **{KIND.get(t.get('kind'), t.get('kind'))}**.\n\n")
        ps = t.get("params") or []
        if ps:
            out.append("| Parameter | Units | Default | Range | What it does |\n|---|---|---|---|---|\n")
            for p in ps:
                d = p.get("digits")
                out.append(f"| **{cell(p.get('label', p['name']))}** | {cell(p.get('units', ''))} | "
                           f"{num(p.get('default'), d)} | {num(p.get('min'), d)} to {num(p.get('max'), d)} | "
                           f"{cell(p.get('help', ''))} |\n")
            out.append("\n")
    (REF / "output-templates.md").write_text("".join(out))


