# Output channels
# ---------------------------------------------------------------------------------------------------
def gen_channels(m):
    tel = m["telemetry"]
    groups = {}
    for name, t in tel.items():
        groups.setdefault(t.get("module") or "Other", []).append((name, t))
    out = [HEADER, "# Output channels\n\n",
           "Every channel the ECU sends to the studio, grouped as the studio groups them. The **name** is\n"
           "what you type in an expression (chapter 34), a Lua script (chapter 35), a CAN field (chapter 33)\n"
           "or a log. **Logged** marks the channels in the ECU's default onboard-log set (chapter 42).\n\n",
           f"{len(tel)} channels.\n\n"]
    for g in sorted(groups):
        out.append(f"## {g}\n\n| Channel | Name | Units | Range | Logged |\n|---|---|---|---|---|\n")
        for name, t in sorted(groups[g], key=lambda kv: kv[1].get("label", kv[0]).lower()):
            d = t.get("digits")
            rng = f"{num(t.get('min'), d)} to {num(t.get('max'), d)}" if "min" in t and "max" in t else ""
            out.append(f"| {cell(t.get('label', name))} | `{name}` | {cell(t.get('units', ''))} | {rng} | "
                       f"{'yes' if t.get('datalog') else ''} |\n")
        out.append("\n")
    (REF / "channels.md").write_text("".join(out))


# ---------------------------------------------------------------------------------------------------
# Trouble codes
# ---------------------------------------------------------------------------------------------------
def code_key(c):
    return int(c[1:], 16)


def gen_dtc(m):
    desc = m["dtc_descriptions"]
    cats = m["dtc_categories"]

    def category(code):
        k = code_key(code)
        for c in cats:
            if code_key(c["lo"]) <= k <= code_key(c["hi"]):
                return c["label"]
        return ""

    out = [HEADER, "# Trouble codes\n\n",
           "Every trouble code this firmware's definition names, with the studio's description and the\n"
           "**Status Lamps** category that lights for it. How codes work — severity, active and stored,\n"
           "clearing — is chapter 44.\n\n",
           "Codes **P0xxx** are the standard OBD-II ones; **P1xxx** are this ECU's own. A sensor's own checks\n"
           "(out of range, not assigned …) use the sensor's standard codes where there are any, and codes\n"
           "in **P1000–P15FF** where there are none.\n\n",
           f"{len(desc)} codes.\n\n",
           "| Code | Description | Lamp |\n|---|---|---|\n"]
    for code in sorted(desc, key=code_key):
        out.append(f"| **{code}** | {cell(desc[code])} | {cell(category(code))} |\n")
    (REF / "dtc.md").write_text("".join(out))


