# Trigger wheels — each drawn over one engine cycle
# ---------------------------------------------------------------------------------------------------
def stream_edges(s):
    """Edge positions in degrees over the stream's own span (360 crank, 720 cam), plus the span.

    gap:   `slots` positions; `gaps` lists the present teeth (by index) that are followed by a gap of
           `ratio` tooth periods — so 36-1 is slots 36, ratio 2, gaps [0]. Ratio 0 is evenly spaced.
    seq:   `cell` is the angle from each edge to the next, in tenths of a degree.
    width: one pulse per cycle.
    `repeats` is how many times the pattern repeats per ENGINE CYCLE (720°), as the firmware reads it
    (GenericTriggerBuilder: repeats, else twice for a crank stream and once for a cam stream).
    The edges returned cover the whole 720° cycle; span is 720."""
    span = 720.0
    reps = int(s.get("repeats", 0) or 0) or (2 if s.get("rate", 0) == 0 else 1)
    part = span / reps
    kind = s.get("kind")
    base = []
    if kind == "gap":
        slots, ratio, gaps = int(s["slots"]), int(s.get("ratio", 0)), list(s.get("gaps", []))
        if ratio <= 1 or not gaps:
            base = [i * part / slots for i in range(slots)]
        else:
            present = slots - len(gaps) * (ratio - 1)
            pos = 0
            for i in range(present):
                base.append(pos * part / slots)
                pos += ratio if i in gaps else 1
    elif kind == "seq":
        cells = [c / 10.0 for c in s["cell"]]
        total = sum(cells) or part
        a = 0.0
        for c in cells:
            base.append(a * part / total)
            a += c
    elif kind == "width":
        base = [0.0]
    edges = [r * part + e for r in range(reps) for e in base]
    return edges, span


def wheel_svg(w):
    W, left, right = 1000, 110, 20
    plot = W - left - right
    rows = w["streams"]
    H = 40 + 60 * len(rows) + 30
    x = lambda deg: left + plot * deg / 720.0
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" '
         "font-family=\"system-ui, -apple-system, 'Segoe UI', Ubuntu, sans-serif\" font-size=\"13\">",
         f"<title>{w['name']}</title>",
         "<style>.fg{fill:#1d1f23}.muted{fill:#5f6670}.axis{stroke:#9aa1ab;stroke-width:1;fill:none}"
         ".tooth{fill:#3b82c4}.cam{fill:#d9822b}.grid{stroke:#c9ced6;stroke-width:1;stroke-dasharray:3 4}"
         "@media (prefers-color-scheme: dark){.fg{fill:#e4e6ea}.muted{fill:#9aa1ab}.grid{stroke:#4a5059}}</style>"]
    for deg in range(0, 721, 90):
        o.append(f'<line x1="{x(deg):.1f}" y1="20" x2="{x(deg):.1f}" y2="{H-26}" class="grid"/>')
        o.append(f'<text x="{x(deg):.1f}" y="{H-8}" text-anchor="middle" class="muted">{deg}°</text>')
    for r, s in enumerate(rows):
        y0 = 40 + 60 * r
        cam = s.get("rate", 0) != 0
        label = "cam" if cam else "crank"
        o.append(f'<text x="10" y="{y0+26}" class="fg">{label}</text>')
        o.append(f'<line x1="{left}" y1="{y0+40}" x2="{left+plot}" y2="{y0+40}" class="axis"/>')
        edges, span = stream_edges(s)
        cls = "cam" if cam else "tooth"
        if s.get("kind") == "width":
            o.append(f'<rect x="{x(0):.1f}" y="{y0+10}" width="{plot*20/720:.1f}" height="30" class="{cls}"/>')
            o.append(f'<text x="{x(30):.1f}" y="{y0+30}" class="muted">one pulse per cycle</text>')
            continue
        both = s.get("edge") == 2 and s.get("kind") == "seq"
        for p in range(1):
            off = 0.0
            if both:
                for i in range(0, len(edges) - 1, 2):
                    a, b = edges[i] + off, edges[i + 1] + off
                    o.append(f'<rect x="{x(a):.1f}" y="{y0+10}" width="{max(1.0, x(b)-x(a)):.1f}" height="30" class="{cls}"/>')
            else:
                # Half the SMALLEST spacing between teeth: an average spreads a clustered pattern's
                # teeth into one solid block.
                gaps_ = [b - a for a, b in zip(edges, edges[1:])] + ([span - edges[-1] + edges[0]] if edges else [])
                pitch = min([g for g in gaps_ if g > 0] or [span])
                tw = max(1.0, min(plot * pitch / 720.0 * 0.5, 14.0))
                for e in edges:
                    o.append(f'<rect x="{x(e + off):.1f}" y="{y0+10}" width="{tw:.1f}" height="30" class="{cls}"/>')
    o.append("</svg>")
    return "\n".join(o)


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def describe(s):
    cam = "cam" if s.get("rate", 0) != 0 else "crank"
    k = s.get("kind")
    reps = int(s.get("repeats", 0) or 0)
    rep = f", {reps} times per engine cycle" if reps else ""
    if k == "gap":
        slots, ratio, gaps = s["slots"], s.get("ratio", 0), s.get("gaps", [])
        if ratio <= 1 or not gaps:
            return f"{cam}: {slots} evenly spaced teeth{rep}"
        missing = len(gaps) * (ratio - 1)
        return f"{cam}: {slots} positions, {slots - missing} teeth, {len(gaps)} gap(s) of {ratio - 1} missing{rep}"
    if k == "seq":
        both = " (both edges)" if s.get("edge") == 2 else ""
        return f"{cam}: {len(s['cell'])} edges at set angles{both}{rep}"
    if k == "width":
        return f"{cam}: one pulse per cycle"
    return f"{cam}: {k}"


def gen_wheels(m):
    WHEELS.mkdir(parents=True, exist_ok=True)
    for f in WHEELS.glob("*.svg"):
        f.unlink()
    out = [HEADER, "# Trigger wheel library\n\n",
           "Every wheel the studio ships in its Trigger Library (chapter 16), drawn over one engine cycle\n"
           "(720°). A crank pattern normally appears twice (once per revolution) and a cam pattern once. The drawing\n"
           "starts at the pattern's reference, not at top dead centre: **Trigger Offset** sets where TDC\n"
           "is (chapter 16). **Crank** sync knows the angle within a revolution; **Phase** sync also knows\n"
           "which revolution, from the cam.\n\n",
           f"{len(m['trigger_wheels'])} wheels.\n\n"]
    for w in m["trigger_wheels"]:
        s = slug(w["name"])
        (WHEELS / f"{s}.svg").write_text(wheel_svg(w))
        sync = "Phase (crank + cam)" if w.get("sync") == "PHASE" else "Crank"
        out.append(f"## {w['name']}\n\n")
        out.append(f"Sync: **{sync}**.")
        if "tdc_offset" in w:
            out.append(f" Library trigger offset: **{w['tdc_offset']:g}°**.")
        out.append("\n\n")
        for st in w["streams"]:
            out.append(f"- {describe(st)}\n")
        out.append(f"\n![{w['name']}: the teeth over one 720° cycle](../img/wheels/{s}.svg)\n\n")
    (REF / "trigger-wheels.md").write_text("".join(out))


