# Appendix: the Proteus F7 board, from its board file
# ---------------------------------------------------------------------------------------------------
def gen_proteus():
    b = yaml.safe_load((ROOT / "definition" / "boards" / "proteus_f7.board.yaml").read_text())
    pins = {p.get("signal"): p for p in b.get("pins", []) if p.get("signal")}
    counts = {}
    # Counted from the CONNECTORS, so an on-board signal (AV12, the ECU's own supply) is not called an input.
    seen = set()
    for t in [t for c in b.get("connectors", []) for t in c.get("terminals", [])]:
        sig = t.get("signal") or ""
        if sig in seen or pins.get(sig, {}).get("assignable") is False:
            continue                                  # a +/- pair is one input; a fixed input is not one
        seen.add(sig)
        m = re.match(r"([A-Z]+)(\d+)$", sig)
        if m:
            counts[m.group(1)] = counts.get(m.group(1), 0) + 1
    out = ["<!-- GENERATED by manual/tools/gen_reference.py from definition/boards/proteus_f7.board.yaml — do not edit. -->\n\n",
           "# Appendix — Proteus F7 board\n\n",
           "The firmware also runs on the **Proteus F7**, an open-hardware ECU board with the same processor\n"
           "(STM32F767). Everything in this manual applies, with these differences:\n\n",
           f"- **Inputs and outputs** — {counts.get('IGN', 0)} ignition, {counts.get('LS', 0)} low-side, "
           f"{counts.get('HS', 0)} high-side outputs; {counts.get('AV', 0)} analogue voltage and "
           f"{counts.get('AT', 0)} temperature inputs; {counts.get('DIG', 0)} digital and "
           f"{counts.get('VR', 0)} VR inputs; two H-bridges; two CAN buses.\n",
           "- **No real-time clock**: the board uses the clock-crystal pins for other signals.\n"
           if not b.get("lse_hz") else "",
           "- **Its pin map is taken from the board's schematic and has not been tested on a running\n"
           "  engine.** Check every input and output on the bench (chapter 43) before trusting it.\n\n",
           "The chapters' pin names (AV1, LS5, IGN3 …) are the same; the connector positions are below.\n\n"]
    for c in b.get("connectors", []):
        out.append(f"## {c['id']} ({c.get('color', '')})\n\n{c.get('desc', '')}\n\n| Pin | Signal |\n|---|---|\n")
        for t in c.get("terminals", []):
            what = t.get("signal") or t.get("role", "")
            if t.get("line"):
                what += f" ({t['line']})"
            if pins.get(t.get("signal"), {}).get("assignable") is False:
                what += " — " + pins[t["signal"]].get("note", "fixed input")
            if t.get("role") == "power" and t.get("voltage"):
                what += f" {t['voltage']} V"
            out.append(f"| {t['pin']} | {cell(what)} |\n")
        out.append("\n")
    (REF / "proteus-f7.md").write_text("".join(out))


def main():
    m = load_meta()
    schema = yaml.safe_load(SCHEMA.read_text())
    gen_channels(m)
    gen_dtc(m)
    gen_sensor_types(schema)
    gen_output_templates(m)
    gen_lua(m)
    gen_wheels(m)
    gen_proteus()
    print(f"reference: {len(m['telemetry'])} channels, {len(m['dtc_descriptions'])} codes, "
          f"{len(schema['sensor_types'])} sensor types, {len(m['output_templates'])} templates, "
          f"{len(m['trigger_wheels'])} wheels -> manual/docs/reference")


if __name__ == "__main__":
    main()
