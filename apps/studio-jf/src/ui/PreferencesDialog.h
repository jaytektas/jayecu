    // Editor→Globals: what a property set to "global" actually resolves to. Built from the property model +
    // TableWidget::globalDefs(), so a new "global" property appears here on its own — the alternative was a
    // hand-kept form, which is how the old resolution rule ended up hand-copied into three places.
    // The stored value is the property's OWN choice index (1..N), so the combo lists choices[1..] and the
    // "global" entry itself is dropped — picking "global" as the answer to "what does global mean" is the
    // circularity this page exists to remove.
    void buildGlobals() {
        using namespace jf;
        m_globalsScroll = std::make_unique<JScrollArea>(m_graph);
        static JSceneGraph s_protoGraph;
        std::unique_ptr<CanvasWidget> proto = makeWidgetInstance("table", s_protoGraph);
        if (!proto) return;
        proto->setScanExcluded(true);
        auto formU = std::make_unique<JContainer>(m_graph);
        JContainer* form = formU.get();
        form->setLayoutMode(JLayoutMode::Form)->setGap(gapV())->setPadding(JEdges{ padV(), padV(), padV(), padV() });

        std::vector<JProperty> props = proto->properties().all();
        std::stable_sort(props.begin(), props.end(), [](const JProperty& a, const JProperty& b){ return a.meta.order < b.meta.order; });
        m_globalsRows = 0;
        for (const JProperty& p : props) {
            if (p.meta.choices.empty()) continue;
            std::vector<std::string> choices; for (const JVariant& cv : p.meta.choices) choices.push_back(cv.toString());
            if (choices.size() < 2 || choices[0] != "global") continue;   // only properties that OFFER "global"

            const std::string key = p.name;
            const int def = TableWidget::globalDefault(key.c_str());
            // A global whose default is 0 answers "follow" rather than a fixed choice (the axis decimals
            // follow the cell's). That answer is offered here as a value — visible and changeable — instead
            // of being a second, hidden meaning of the word "global".
            const bool follows = (def == 0);
            std::vector<std::string> opts;
            if (follows) opts.push_back("follow the cell");
            for (size_t i = 1; i < choices.size(); ++i) opts.push_back(choices[i]);

            const int stored = EditorSettings::instance().propGlobal("table." + key, def);
            // store value v == choices[v]; with a "follow" entry at 0 the combo indexes line up, otherwise
            // the combo is shifted by the dropped "global" entry.
            const int idx = follows ? stored : stored - 1;

            form->add(std::make_unique<JLabel>(m_graph, p.meta.label.empty() ? key : p.meta.label, 150.f));
            JComboBox* cp = form->add(std::make_unique<JComboBox>(m_graph, opts));
            cp->setCurrentIndex(std::clamp(idx, 0, static_cast<int>(opts.size()) - 1));
            cp->onIndexChanged.connect([key, follows](int i) {
                EditorSettings::instance().setPropGlobal("table." + key, follows ? i : i + 1);
            });
            m_globalsRows++;
        }
        form->setBounds({ 0.f, 0.f, 300.f, padV()*2.f + (m_globalsRows + 1) * (rowH() + gapV()) });
        m_globalsScroll->addChildWidget(std::move(formU));
    }

