    void buildConnection() {
        using namespace jf;
        JContainer* f = m_pages[2].get();
        f->setLayoutMode(JLayoutMode::Form)->setGap(gapV())->setPadding(JEdges{ padV(), padV(), padV(), padV() });
        auto& s = JSettings::instance();
        // WHICH PORT. Automatic is right whenever the studio can tell which device is an ECU — it
        // prefers the jayecu CDC descriptor and, when several answer, asks. But it cannot always tell:
        // a port with no usable descriptor is indistinguishable from any other, and the studio then
        // picks one and opens it. Naming the port ends the guessing, and it is also the only way to
        // say "that one" when two ECUs are on the bench and both are the same hardware.
        //
        // The list is read when the dialog opens, so plugging an ECU in and reopening this page shows
        // it. A remembered port that is not present right now is kept in the list and marked, rather
        // than silently dropped — forgetting the choice because the ECU is unplugged is how a setting
        // becomes something you have to set twice.
        f->add(std::make_unique<JLabel>(m_graph, "Serial port", 240.f));
        m_portIds.clear();
        std::vector<std::string> portLabels{ "Automatic" };
        m_portIds.push_back("");
        const std::string savedPort = s.get<std::string>("connection.port", std::string());
        bool savedSeen = false;
        for (const auto& info : jf::JSerialPort::availablePorts()) {
            if (!DeviceScanner::isUsbSerial(info)) continue;
            std::string label = info.port;
            if (info.hasVidPid) {
                char ids[16];
                std::snprintf(ids, sizeof ids, "%04x:%04x", info.vendorId, info.productId);
                label += "  (" + std::string(ids);
                if (info.vendorId == 0x0483 && info.productId == 0x5740) label += ", jayecu";
                label += ")";
            } else if (!info.description.empty() && info.description != info.port) {
                label += "  (" + info.description + ")";
            }
            portLabels.push_back(label);
            m_portIds.push_back(info.port);
            if (info.port == savedPort) savedSeen = true;
        }
        if (!savedPort.empty() && !savedSeen) {           // remembered, but not plugged in at the moment
            portLabels.push_back(savedPort + "  (not connected)");
            m_portIds.push_back(savedPort);
        }
        JComboBox* port = f->add(std::make_unique<JComboBox>(m_graph, portLabels));
        for (size_t i = 0; i < m_portIds.size(); ++i)
            if (m_portIds[i] == savedPort) { port->setCurrentIndex(static_cast<int>(i)); break; }
        port->onIndexChanged.connect([this](int i) {
            const std::string sel = (i >= 0 && i < static_cast<int>(m_portIds.size())) ? m_portIds[size_t(i)]
                                                                                       : std::string();
            JSettings::instance().set("connection.port", JVariant(sel));
        });

        f->add(std::make_unique<JLabel>(m_graph, "Reopen last project on launch", 240.f));
        JCheckBox* reopen = f->add(std::make_unique<JCheckBox>(m_graph, "", 30.f));
        reopen->setChecked(s.get<bool>("startup.reopenLastProject", false));
        reopen->onStateChanged.connect([](bool on) { JSettings::instance().set("startup.reopenLastProject", on); });
        f->add(std::make_unique<JLabel>(m_graph, "Connect automatically on launch", 240.f));
        JCheckBox* autoc = f->add(std::make_unique<JCheckBox>(m_graph, "", 30.f));
        autoc->setChecked(s.get<bool>("connection.autoConnect", false));
        autoc->onStateChanged.connect([](bool on) { JSettings::instance().set("connection.autoConnect", on); });
        // WHICH protocol the connect button probes with. Off, it follows the loaded schema: a definition
        // imported from a .ini carries a tsProtocol block and gets the TunerStudio handshake, anything else
        // gets the native identity request. That is fine until the studio comes up on the built-in schema
        // with a rusEFI ECU on the bench, where the native request is answered with silence and the button
        // reports "ECU did not identify". On, the signature query goes first regardless, and the definition
        // matching whatever answers is loaded from the imported library.
        f->add(std::make_unique<JLabel>(m_graph, "Probe with rusEFI / TunerStudio protocol", 240.f));
        JCheckBox* tsProbe = f->add(std::make_unique<JCheckBox>(m_graph, "", 30.f));
        tsProbe->setChecked(s.get<bool>("connection.rusefiProbe", false));
        tsProbe->onStateChanged.connect([](bool on) { JSettings::instance().set("connection.rusefiProbe", on); });

        // Engine-cycle recorder depth. How much history is worth holding depends on what is being
        // chased: a drifting spark shows up in a handful of cycles, an intermittent misfire needs a
        // long tail. Each frame is one captured cycle held in the studio, so this is memory, not
        // load on the ECU — the ECU still records exactly one cycle per request either way.
        f->add(std::make_unique<JLabel>(m_graph, "Engine cycle frames to keep", 240.f));
        JComboBox* frames = f->add(std::make_unique<JComboBox>(
            m_graph, std::vector<std::string>{ "20", "60", "120", "300" }));
        const int cur = s.get<int>("engineCycle.frames", 60);
        frames->setCurrentIndex(cur <= 20 ? 0 : cur <= 60 ? 1 : cur <= 120 ? 2 : 3);
        frames->onIndexChanged.connect([](int i) {
            static const int kFrames[] = { 20, 60, 120, 300 };
            JSettings::instance().set("engineCycle.frames", kFrames[i < 0 ? 1 : (i > 3 ? 3 : i)]);
        });
        m_rows[2] = 5;
    }

