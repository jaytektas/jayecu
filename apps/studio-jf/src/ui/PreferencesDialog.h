    // Editor→Widget Defaults: MASTER-DETAIL. The master is a list of widget types; the detail is the ONE real
    // property inspector (PropertiesDock) pointed at a live PROTOTYPE instance of the selected type. Editing a
    // prototype's properties IS editing that type's creation defaults — no bespoke form. On a new widget the
    // prototype's props (minus uid/x/y) are copied over (persisted here into EditorSettings::widgetDefaultProps).
    void buildWidgetDefaults() {
        using namespace jf;
        m_wdefModel = std::make_unique<PanelModel>();
        std::vector<std::string> labels;
        for (const std::string& t : widgetTypes()) {
            m_types.push_back(t);
            const std::string title = widgetTitle(t);
            labels.push_back(title.empty() ? t : title);
            int dw = 160, dh = 90;
            if (auto proto = makeWidgetInstance(t, m_graph)) { dw = static_cast<int>(proto->defaultW()); dh = static_cast<int>(proto->defaultH()); }
            EditorSettings::instance().widgetDefaultSize(t, dw, dh);   // stored size overrides the class default
            m_wdefElem[t] = m_wdefModel->add(t, 0.f, 0.f, static_cast<float>(dw), static_cast<float>(dh),
                                             EditorSettings::instance().widgetDefaultProps(t));   // seed the prototype
        }
        m_typeList = std::make_unique<JListView>(m_graph, labels);
        m_typeList->onSelectionChanged.connect([this](int i) { if (i >= 0 && i < static_cast<int>(m_types.size())) m_wdefPending = m_types[i]; });

        m_wdefProps = std::make_unique<PropertiesDock>(m_graph);
        // Every edit persists the prototype's props as the type's defaults (no undo stack, no surface).
        m_wdefProps->onApplyEdit = [this](const std::string&, const std::vector<PanelElement>&, int){ persistPrototype(m_wdefCurrentType); };

        if (!m_types.empty()) { m_typeList->setSelectedIndex(0); m_wdefPending = m_types[0]; }
    }

    // Point the detail inspector at the selected type's prototype element (deferred out of the click handler).
    void showWidgetDefault(const std::string& type) {
        m_wdefCurrentType = type;
        auto it = m_wdefElem.find(type);
        if (it != m_wdefElem.end() && m_wdefProps) m_wdefProps->showFor(m_wdefModel.get(), { it->second }, true);
    }

    // Serialise the edited prototype back to the type's stored defaults: props (minus geometry/uid/empties) and size.
    void persistPrototype(const std::string& type) {
        if (type.empty() || !m_wdefModel) return;
        auto it = m_wdefElem.find(type);
        if (it == m_wdefElem.end()) return;
        const PanelElement* e = m_wdefModel->get(it->second);
        if (!e) return;
        std::unordered_map<std::string, std::string> props;
        for (const auto& [k, v] : e->props)
            if (k != "x" && k != "y" && k != "w" && k != "h" && k != "uid" && !v.empty()) props[k] = v;
        EditorSettings::instance().setWidgetDefaultProps(type, props);
        EditorSettings::instance().setWidgetDefaultSize(type, static_cast<int>(e->w), static_cast<int>(e->h));
    }

    // Fill a Form container with a widget type's creation-default controls: the default size, then one row per
    // editable property of the widget CLASS's JPropertyModel (order-sorted). Ownership goes into the passed
    // vectors. Returns row count. The TABLES page only — Widget Defaults drives a prototype element through the
    // shared inspector instead. A stored EditorSettings default overrides
    // the class's authored default (JPropertyMeta.def) for the initial value.
    int fillSchemaControls(jf::JContainer* form, const std::string& type) {
        using namespace jf;
        static JSceneGraph s_protoGraph;
        std::unique_ptr<CanvasWidget> proto = makeWidgetInstance(type, s_protoGraph);
        if (!proto) return 0;
        // A PROTOTYPE: constructed only to read its class defaults + property model, never laid out or
        // painted. It still registers in the global widget set, so keep it out of focus/hit scans.
        proto->setScanExcluded(true);
        int rows = 0;
        // Default width / height — the widget class's drop size, overridden by any stored Widget-Defaults size.
        int dw = static_cast<int>(proto->defaultW()), dh = static_cast<int>(proto->defaultH());
        EditorSettings::instance().widgetDefaultSize(type, dw, dh);
        form->add(std::make_unique<JLabel>(m_graph, "Default width", 150.f));
        JSpinBox* wp = form->add(std::make_unique<JSpinBox>(m_graph, 1, 10000, 100.f)); wp->setValue(dw); rows++;
        form->add(std::make_unique<JLabel>(m_graph, "Default height", 150.f));
        JSpinBox* hp = form->add(std::make_unique<JSpinBox>(m_graph, 1, 10000, 100.f)); hp->setValue(dh); rows++;
        auto commitSize = [wp, hp, type] { EditorSettings::instance().setWidgetDefaultSize(type, wp->value(), hp->value()); };
        wp->onValueChanged.connect([commitSize](int){ commitSize(); });
        hp->onValueChanged.connect([commitSize](int){ commitSize(); });

        // Per-property creation defaults from the widget class's JPropertyModel, sorted by meta.order.
        const auto stored = EditorSettings::instance().widgetDefaultProps(type);
        std::vector<JProperty> props = proto->properties().all();
        std::stable_sort(props.begin(), props.end(), [](const JProperty& a, const JProperty& b){ return a.meta.order < b.meta.order; });
        for (const JProperty& p : props) {
            if (!p.writable()) continue;
            const std::string& k = p.name;
            if (k=="x"||k=="y"||k=="w"||k=="h"||k=="uid"||k=="value"||k=="aspectRatioLocked") continue;
            if (k=="labelText"||k=="text"||k=="buttonText"||k=="title") continue;
            const std::string& ed = p.meta.editor;
            if (ed=="signal"||ed=="unit"||ed=="file") continue;
            const auto sit = stored.find(k);
            const std::string v = (sit != stored.end()) ? sit->second : p.meta.def;
            const std::string lbl = p.meta.label.empty() ? k : p.meta.label;
            const std::string key = k;
            if (ed == "color") {
                form->add(std::make_unique<JLabel>(m_graph, lbl, 150.f));
                JColorButton* cbp = form->add(std::make_unique<JColorButton>(m_graph, 170.f));
                cbp->setInheritable(p.meta.inheritable); cbp->setColorHex(v);
                cbp->onColorChanged.connect([key, type](const std::string& hex){ auto m = EditorSettings::instance().widgetDefaultProps(type); m[key] = hex; EditorSettings::instance().setWidgetDefaultProps(type, m); });
                rows++;
            } else if (ed == "font") {
                form->add(std::make_unique<JLabel>(m_graph, lbl, 150.f));
                JFontButton* fbp = form->add(std::make_unique<JFontButton>(m_graph, 170.f));
                fbp->setInheritable(p.meta.inheritable); fbp->setFontSpec(v);
                fbp->onFontChanged.connect([key, type](const std::string& spec){ auto m = EditorSettings::instance().widgetDefaultProps(type); m[key] = spec; EditorSettings::instance().setWidgetDefaultProps(type, m); });
                rows++;
            } else if (!p.meta.choices.empty() || ed == "choices") {
                std::vector<std::string> choices; for (const JVariant& cv : p.meta.choices) choices.push_back(cv.toString());
                if (choices.empty()) continue;
                int idx = 0; try { idx = std::stoi(v); } catch (...) { for (size_t kk=0;kk<choices.size();++kk) if (choices[kk]==v) idx=static_cast<int>(kk); }
                form->add(std::make_unique<JLabel>(m_graph, lbl, 150.f));
                JComboBox* cp = form->add(std::make_unique<JComboBox>(m_graph, choices));
                cp->setCurrentIndex(std::clamp(idx, 0, static_cast<int>(choices.size())-1));
                cp->onIndexChanged.connect([key, type](int i){ auto m = EditorSettings::instance().widgetDefaultProps(type); m[key] = std::to_string(i); EditorSettings::instance().setWidgetDefaultProps(type, m); });
                rows++;
            } else if (p.get().isBool()) {
                form->add(std::make_unique<JLabel>(m_graph, lbl, 150.f));
                JCheckBox* c = form->add(std::make_unique<JCheckBox>(m_graph, "", 30.f)); c->setChecked(v=="1"||v=="true");
                c->onStateChanged.connect([key, type](bool on){ auto m = EditorSettings::instance().widgetDefaultProps(type); m[key] = on?"1":"0"; EditorSettings::instance().setWidgetDefaultProps(type, m); });
                rows++;
            } else if (p.get().isNumber()) {
                form->add(std::make_unique<JLabel>(m_graph, lbl, 150.f));
                JSpinBox* spp = form->add(std::make_unique<JSpinBox>(m_graph, static_cast<int>(p.meta.min.toDouble(0)), static_cast<int>(p.meta.max.toDouble(100)), 100.f));
                int iv = 0; try { iv = static_cast<int>(std::stod(v)); } catch (...) {} spp->setValue(iv);
                spp->onValueChanged.connect([key, type](int nv){ auto m = EditorSettings::instance().widgetDefaultProps(type); m[key] = std::to_string(nv); EditorSettings::instance().setWidgetDefaultProps(type, m); });
                rows++;
            }
            // else: a plain-text property — the old form rendered no control for these; skip (unchanged).
        }
        return rows;
    }

